    $num = [System.Text.RegularExpressions.Regex]::Match($file.BaseName, "\d+").Value
    if ($num) {
        $numPadded = $num.PadLeft(3, '0')
        if ($itemsMap.ContainsKey($numPadded)) {
            $productName = $itemsMap[$numPadded]
        } else {
            $productName = "Product Variant Packshot (Item #$numPadded)"
